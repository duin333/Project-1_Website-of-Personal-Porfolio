export function readRoute(hash = "") {
  const match = hash.match(/^#?\/(vi|en|ja)(?:\/projects\/([a-z0-9-]+))?\/?$/);
  return match
    ? {
        lang: match[1],
        project: projects.some((p) => p.id === match[2]) ? match[2] : null,
      }
    : null;
}
export function projectRoute(lang, id) {
  return `/${lang}${id ? `/projects/${id}` : ""}`;
}

